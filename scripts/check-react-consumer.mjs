import { mkdtemp, readdir, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join, resolve } from "node:path";
import { execFileSync } from "node:child_process";

const reactVersion = process.env.REACT_VERSION ?? "18";
const xrplVersion = process.env.XRPL_VERSION ?? "4";
const directory = await mkdtemp(join(tmpdir(), `xwk-react-${reactVersion}-`));
const packs = resolve(process.env.PACK_DIRECTORY ?? ".packs");
const tarballs = (await readdir(packs)).filter((file) => file.endsWith(".tgz")).map((file) => `file:${join(packs, file)}`);
const commandOptions = (cwd) => ({ cwd, stdio: "inherit", shell: process.platform === "win32" });

await writeFile(join(directory, "package.json"), JSON.stringify({ private: true, type: "module" }));
execFileSync("npm", ["install", "--ignore-scripts", "--strict-peer-deps", "--legacy-peer-deps=false", "--no-audit", "--no-fund", "--fetch-timeout=20000", "--fetch-retries=1", `react@${reactVersion}`, `react-dom@${reactVersion}`, `@types/react@${reactVersion}`, "@types/node@20", "typescript@5.5", "vue@3", `xrpl@${xrplVersion}`, ...tarballs], { ...commandOptions(directory), timeout: 120000 });
await writeFile(join(directory, "tsconfig.json"), JSON.stringify({ compilerOptions: { strict: true, jsx: "react-jsx", module: "NodeNext", moduleResolution: "NodeNext", target: "ES2022", skipLibCheck: false }, include: ["consumer.tsx"] }));
await writeFile(join(directory, "consumer.tsx"), `import { createRef } from "react";\nimport { WalletButton, type WalletButtonHandle } from "@xrpl-wallet-kit/react";\nimport { WalletButton as NextWalletButton } from "@xrpl-wallet-kit/next";\nconst ref = createRef<WalletButtonHandle>();\nvoid <WalletButton ref={ref} className="slot" aria-label="Wallet" data-testid="wallet" />;\nvoid <NextWalletButton style={{ display: "inline-flex" }} />;\n`);
execFileSync(join(directory, "node_modules", ".bin", process.platform === "win32" ? "tsc.cmd" : "tsc"), ["--noEmit"], commandOptions(directory));
await writeFile(join(directory, "vue-consumer.ts"), `import { createSSRApp, h } from "vue";
import { WalletManager } from "@xrpl-wallet-kit/core";
import { createWalletKitPlugin, WalletButton, useWalletKit } from "@xrpl-wallet-kit/vue";
import type { AccountSet } from "xrpl";
const manager = new WalletManager({ adapters: [] });
createSSRApp({ render: () => h(WalletButton) }).use(createWalletKitPlugin({ manager }));
const tx: AccountSet = { TransactionType: "AccountSet", Account: "rHb9CJAWyB4rj91VRWn96DkukG4bwdtyTh" };
void manager.signTransaction({ txJson: tx });
void useWalletKit;
`);
execFileSync(join(directory, "node_modules", ".bin", process.platform === "win32" ? "tsc.cmd" : "tsc"), ["--noEmit", "--strict", "--module", "NodeNext", "--moduleResolution", "NodeNext", "--target", "ES2022", "vue-consumer.ts"], commandOptions(directory));
await writeFile(join(directory, "codec.mjs"), `import assert from "node:assert/strict";
import { Wallet, encode, decode } from "xrpl";
import { normalizeSignTransactionResult } from "@xrpl-wallet-kit/core";
const wallet = Wallet.generate();
const tx = { TransactionType: "AccountSet", Account: wallet.classicAddress, Sequence: 1, Fee: "12", LastLedgerSequence: 100 };
assert.equal(decode(encode(tx)).Account, wallet.classicAddress);
const signed = wallet.sign(tx);
assert.equal(decode(signed.tx_blob).Account, wallet.classicAddress);
assert.equal(normalizeSignTransactionResult({ txBlob: signed.tx_blob }).txBlob, signed.tx_blob);
`);
execFileSync(process.execPath, ["codec.mjs"], commandOptions(directory));
