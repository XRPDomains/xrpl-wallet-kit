import assert from "node:assert/strict";
import { createRequire } from "node:module";
import { readFile } from "node:fs/promises";

const require = createRequire(import.meta.url);
const { chromium } = require(process.env.PLAYWRIGHT_MODULE ?? "playwright");
const base = process.env.WEBSITE_URL ?? "http://127.0.0.1:5176/xrpl-wallet-kit/";
const bundle = await readFile(new URL("../packages/browser/dist/xrpl-wallet-kit.iife.min.js", import.meta.url));
const browser = await chromium.launch({ headless: true, executablePath: process.env.PLAYWRIGHT_EXECUTABLE_PATH });
try {
  for (const viewport of [{ width: 1440, height: 900 }, { width: 390, height: 844 }]) {
    const page = await browser.newPage({ viewport });
    const errors = [];
    page.on("pageerror", error => errors.push(error.message));
    await page.route("**/xrpl-wallet-kit.iife.min.js", route => route.fulfill({ contentType: "application/javascript", body: bundle }));
    await page.goto(new URL("docs/theme-builder", base).href);
    await page.locator('.tb-root [data-wallet-id="joey-wallet"]').waitFor();
    const joey = page.locator(".tb-wallet-option").filter({ hasText: "Joey Wallet" }).locator("input");
    assert.equal(await joey.isChecked(), true);
    const clasp = page.locator(".tb-wallet-option").filter({ hasText: "Clasp" }).locator("input");
    assert.equal(await clasp.isChecked(), true);
    await page.locator('.tb-root [data-wallet-id="clasp"]').waitFor();
    assert.match(await page.locator(".tb-code").textContent(), /manager\.register\(createClaspAdapter\(\)\)/);
    assert.doesNotMatch(await page.locator(".tb-code").textContent(), /"clasp"/);
    await clasp.uncheck();
    await page.waitForFunction(() => !document.querySelector('.tb-root [data-wallet-id="clasp"]'));
    assert.doesNotMatch(await page.locator(".tb-code").textContent(), /createClaspAdapter/);
    await clasp.check();
    await page.locator('.tb-root [data-wallet-id="clasp"]').waitFor();
    const privy = page.locator(".tb-wallet-option").filter({ hasText: "Privy" }).locator("input");
    const privyRow = page.locator('.tb-root [data-wallet-id="privy"]');
    const code = page.locator(".tb-code");
    assert.equal(await privy.isChecked(), true);
    await privyRow.waitFor();
    assert.match(await code.textContent(), /manager\.register\(createPrivyAdapter\(/);
    assert.match(await code.textContent(), /YOUR_PUBLIC_PRIVY_APP_ID/);
    await privyRow.click();
    await page.getByRole("textbox", { name: "Email address" }).waitFor();
    await page.locator('.tb-root [data-xwk-back]').click();
    await privyRow.waitFor();
    assert.doesNotMatch(await code.textContent(), /"privy",/);
    await page.locator("#tb-network").selectOption("testnet");
    await privyRow.waitFor();
    assert.match(await code.textContent(), /network: "testnet"/);
    assert.match(await code.textContent(), /createPrivyAdapter/);
    await privy.uncheck();
    await privyRow.waitFor({ state: "detached" });
    assert.doesNotMatch(await code.textContent(), /createPrivyAdapter/);
    await privy.check();
    await privyRow.waitFor();
    await page.locator("#tb-network").selectOption("mainnet");
    await privyRow.waitFor();
    const layout = page.locator(".tb-section").filter({ has: page.getByText("Layout", { exact: true }) }).locator("select");
    assert.deepEqual(await layout.locator("option").evaluateAll(options => options.map(option => option.value)), ["auto", "list", "card", "icon"]);
    assert.equal(await layout.inputValue(), "auto");
    assert.match(await page.locator(".tb-code").textContent(), /layout: "auto"/);
    assert.match(await page.locator(".tb-code").textContent(), /"joey-wallet"/);
    await page.locator(".tb-root .xwk-layout-card").waitFor();
    await joey.uncheck();
    await page.waitForFunction(() => !document.querySelector('.tb-root [data-wallet-id="joey-wallet"]'));
    await joey.check();
    await page.locator('.tb-root [data-wallet-id="joey-wallet"]').waitFor();
    await page.locator(".tb-root").evaluate(root => { root.scrollTop = 0; });
    await page.waitForFunction(() => {
      const modal = document.querySelector(".tb-root .xwk-modal");
      const overlay = modal?.closest(".xwk-overlay");
      return modal && overlay && getComputedStyle(modal).opacity === "1" && getComputedStyle(overlay).opacity === "1";
    });
    await page.screenshot({ path: `tmp/theme-builder-auto-${viewport.width}.png`, fullPage: true });
    await page.locator("#tb-chain").selectOption("xahau");
    await page.locator(".tb-root .xwk-layout-list").waitFor();
    assert.equal(await page.locator('.tb-root [data-wallet-id="joey-wallet"]').count(), 0);
    assert.equal(await page.locator('.tb-root [data-wallet-id="clasp"]').count(), 0);
    assert.equal(await page.locator(".tb-wallet-option").filter({ hasText: "Clasp" }).count(), 0);
    assert.equal(await privyRow.count(), 0);
    assert.equal(await privy.count(), 0);
    assert.doesNotMatch(await code.textContent(), /createPrivyAdapter/);
    await page.goto(new URL("docs/playground", base).href);
    await page.locator(".pg-code").waitFor();
    const choices = page.locator(".pg-chips").first().locator("button");
    assert.deepEqual(await choices.allTextContents().then(values => values.map(value => value.trim())), ["Auto", "List", "Card", "Icon"]);
    assert.equal(await choices.first().evaluate(button => button.classList.contains("pg-chip") && button.classList.contains("active")), true);
    assert.match(await page.locator(".pg-code").textContent(), /layout: "auto"/);
    assert.deepEqual(errors, []);
    console.log(`${viewport.width}px: wallet selection and preview (including Privy), adaptive layout, Xahau filtering and Playground controls passed`);
    await page.close();
  }
} finally {
  await browser.close();
}
